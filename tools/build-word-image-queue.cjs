'use strict';

const fs = require('node:fs');
const path = require('node:path');
const { normalizeWord } = require('./audit-word-images.cjs');

function buildQueue(audit, previous) {
  const old = new Map(((previous && previous.items) || []).map(item => [item.id, item]));
  const grouped = new Map();
  for (const entry of audit.entries || []) {
    if (!entry.needsGeneration && entry.sourceType !== 'generated-png' && entry.status !== 'generated') continue;
    let item = grouped.get(entry.sharedKey);
    if (!item) {
      item = {
        id: entry.sharedKey,
        category: entry.category,
        norwegian: entry.norwegian,
        ukrainian: entry.ukrainian,
        english: entry.english,
        filename: entry.filename,
        generatedPath: entry.generatedPath,
        prompt: entry.prompt,
        wordIds: [],
        status: entry.status === 'generated' || entry.sourceType === 'generated-png' ? 'generated' : 'pending',
        attempts: 0,
        error: null,
        outputHint: null,
        updatedAt: null
      };
      const prior = old.get(item.id);
      if (prior && prior.generatedPath === item.generatedPath && prior.prompt === item.prompt) {
        for (const key of ['status', 'attempts', 'error', 'outputHint', 'updatedAt']) {
          if (Object.prototype.hasOwnProperty.call(prior, key)) item[key] = prior[key];
        }
      }
      grouped.set(entry.sharedKey, item);
    }
    item.wordIds.push(entry.id);
    if (entry.status === 'generated' || entry.sourceType === 'generated-png') {
      item.status = 'generated';
      item.error = null;
    }
  }
  const items = [...grouped.values()];
  const now = new Date().toISOString();
  return {
    version: 1,
    createdAt: previous && previous.createdAt ? previous.createdAt : now,
    updatedAt: now,
    batchSize: 25,
    stats: {
      total: items.length,
      pending: items.filter(x => x.status === 'pending').length,
      generated: items.filter(x => x.status === 'generated').length,
      failed: items.filter(x => x.status === 'failed').length,
      generating: items.filter(x => x.status === 'generating').length
    },
    items
  };
}

function buildMapping(audit) {
  const grouped = new Map();
  for (const entry of audit.entries || []) {
    if (entry.status !== 'generated' && entry.sourceType !== 'generated-png') continue;
    const word = normalizeWord(entry.norwegian);
    const value = { src: String(entry.image).replace(/\\/g, '/'), uk: String(entry.ukrainian || '') };
    const list = grouped.get(word) || [];
    if (!list.some(x => x.src === value.src && x.uk === value.uk)) list.push(value);
    grouped.set(word, list);
  }
  const result = {};
  for (const [word, values] of [...grouped.entries()].sort(([a], [b]) => a.localeCompare(b, 'nb'))) {
    result[word] = values.length === 1 ? values[0].src : values;
  }
  return result;
}

function mappingModule(mapping) {
  return `/* Generated by tools/build-word-image-queue.cjs. Do not edit by hand. */\n` +
    `(() => {\n  'use strict';\n  if (!window.KomiksPics || !window.KomiksPics.addPhotos) return;\n` +
    `  window.KomiksPics.addPhotos(${JSON.stringify(mapping, null, 2)});\n})();\n`;
}

function ensureIndexEntry(source) {
  if (source.includes('data/word-images-generated.js')) return source;
  const anchor = /([ \t]*["']data\/word-photos\.js["'],?\r?\n)/;
  if (!anchor.test(source)) throw new Error('data/word-photos.js not found in data/index.js');
  return source.replace(anchor, `$1    "data/word-images-generated.js",\n`);
}

function main() {
  const root = path.resolve(process.argv[2] || path.join(__dirname, '..'));
  const auditPath = path.join(root, 'reports/image-audit.json');
  const queuePath = path.join(root, 'reports/image-generation-queue.json');
  const mappingPath = path.join(root, 'data/word-images-generated.js');
  const indexPath = path.join(root, 'data/index.js');
  const audit = JSON.parse(fs.readFileSync(auditPath, 'utf8'));
  const previous = fs.existsSync(queuePath) ? JSON.parse(fs.readFileSync(queuePath, 'utf8')) : null;
  const built = buildQueue(audit, previous);
  fs.writeFileSync(queuePath, JSON.stringify(built, null, 2) + '\n');
  fs.writeFileSync(mappingPath, mappingModule(buildMapping(audit)));
  fs.writeFileSync(indexPath, ensureIndexEntry(fs.readFileSync(indexPath, 'utf8')));
  process.stdout.write(`Queue: ${built.stats.total} unique assets; ${built.stats.pending} pending, ${built.stats.generated} generated, ${built.stats.failed} failed.\n`);
}

module.exports = { buildQueue, buildMapping, mappingModule, ensureIndexEntry };
if (require.main === module) main();

